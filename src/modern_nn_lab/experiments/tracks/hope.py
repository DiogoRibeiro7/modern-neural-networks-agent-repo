"""Experiment suite for Track 06 — Nested Learning.

**Research prototype.** The formalization audit that this suite implements is in
[`docs/nested_learning_audit.md`](../../../../docs/nested_learning_audit.md), and it was
written before any code, as the track prompt requires.

The experiment is a continual stream: a sequence of unrelated linear tasks presented one
after another, with no task boundaries given to the learner. The headline metric is the
mean squared error across **all** tasks after the whole stream has been seen, which is a
retention measure rather than a plasticity one.

The comparison is between learners that differ *only* in their level structure:

- ``one-level`` — plain gradient descent (source eqs. 1, 8).
- ``two-level`` — gradient descent with momentum, i.e. adding an L1 associative memory
  over gradients (eqs. 10-13).
- ``two-level-slow`` — the same, with L1 updating once every four samples, which is what
  "nested timescales" means operationally.
- ``two-level-reset`` — the same, but L1 is discarded at every task boundary. The source
  argues knowledge about the loss landscape lives in the momentum state; this variant is
  the direct test of that *consequence*.
- ``self-referential`` — the equation-58 rule, whose target values are generated by the
  memory's own state.

Every learner selects its learning rate from the same grid on a validation stream, because
the two-level learner's effective step is ``eta / (1 - decay)`` and a shared rate would
compare step sizes rather than level structures.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import torch
from torch import Tensor

from modern_nn_lab.experiments.data import SupervisedSplit
from modern_nn_lab.experiments.evaluation import mean_squared_error
from modern_nn_lab.experiments.external import run_external_baseline
from modern_nn_lab.experiments.records import ARTEFACT_DIRNAME, RESULT_SCHEMA_VERSION
from modern_nn_lab.experiments.runner import RunGroup, RunSpec
from modern_nn_lab.reproducibility import seed_everything
from modern_nn_lab.tracks.hope import LearnerConfig, NestedLearner, SelfReferentialLearner

TRACK = "hope"
ARCHITECTURE_VERSION = "0.1.0"

LearnerFactory = Callable[[LearnerConfig], NestedLearner]


@dataclass(frozen=True, slots=True)
class ContinualStream:
    """A sequence of unrelated linear tasks presented back to back.

    Attributes:
        inputs: Shape ``(n_tasks * samples, d_in)``, in stream order.
        targets: Shape ``(n_tasks * samples, d_out)``, in stream order.
        task_index: Shape ``(n_tasks * samples,)`` giving each sample's task.
        test_inputs: Shape ``(n_tasks * test_samples, d_in)``.
        test_targets: Matching targets.
        test_task_index: Task of each test sample.
        n_tasks: Number of tasks.
        samples_per_task: Training samples per task.
    """

    inputs: Tensor
    targets: Tensor
    task_index: Tensor
    test_inputs: Tensor
    test_targets: Tensor
    test_task_index: Tensor
    n_tasks: int
    samples_per_task: int


def make_continual_stream(
    *,
    n_tasks: int = 4,
    samples_per_task: int = 200,
    test_samples: int = 60,
    d_in: int = 8,
    d_out: int = 4,
    seed: int = 1729,
    conflicting: bool = False,
) -> ContinualStream:
    """Build a stream of linear tasks with no boundary markers.

    Args:
        n_tasks: Number of tasks in the stream.
        samples_per_task: Training samples per task.
        test_samples: Held-out samples per task.
        d_in: Input width.
        d_out: Output width.
        seed: Generator seed.
        conflicting: When true, every second task is the *negation* of the previous one,
            so the two tasks demand opposite mappings from the same inputs. This is the
            prompt's "conflicting tasks" diagnostic.

    Returns:
        A :class:`ContinualStream`.

    Raises:
        ValueError: If any dimension is not positive.
    """

    if min(n_tasks, samples_per_task, test_samples, d_in, d_out) <= 0:
        raise ValueError("all stream dimensions must be positive")

    generator = torch.Generator().manual_seed(seed)
    maps: list[Tensor] = []
    for index in range(n_tasks):
        if conflicting and index % 2 == 1:
            maps.append(-maps[-1])
        else:
            maps.append(torch.randn((d_out, d_in), generator=generator) / d_in**0.5)

    train_inputs, train_targets, train_tasks = [], [], []
    test_inputs, test_targets, test_tasks = [], [], []
    for index, mapping in enumerate(maps):
        block = torch.randn((samples_per_task, d_in), generator=generator)
        train_inputs.append(block)
        train_targets.append(block @ mapping.T)
        train_tasks.append(torch.full((samples_per_task,), index))

        held = torch.randn((test_samples, d_in), generator=generator)
        test_inputs.append(held)
        test_targets.append(held @ mapping.T)
        test_tasks.append(torch.full((test_samples,), index))

    return ContinualStream(
        inputs=torch.cat(train_inputs),
        targets=torch.cat(train_targets),
        task_index=torch.cat(train_tasks),
        test_inputs=torch.cat(test_inputs),
        test_targets=torch.cat(test_targets),
        test_task_index=torch.cat(test_tasks),
        n_tasks=n_tasks,
        samples_per_task=samples_per_task,
    )


def stream_to_split(stream: ContinualStream, *, name: str) -> SupervisedSplit:
    """Wrap a stream as a split so it flows through the shared record machinery.

    The training tensors keep **stream order** — shuffling them would destroy the
    continual-learning structure — and the test set is the union of every task's held-out
    samples, so the primary metric is retention across all tasks rather than performance
    on the most recent one.

    Args:
        stream: The stream to wrap.
        name: Dataset label.

    Returns:
        A :class:`SupervisedSplit`. Validation reuses the test inputs of the *first* task
        only, which is enough to rank learning rates without touching the full test set.
    """

    first_task = stream.test_task_index == 0
    return SupervisedSplit(
        name=name,
        train_inputs=stream.inputs,
        train_targets=stream.targets,
        val_inputs=stream.test_inputs[first_task],
        val_targets=stream.test_targets[first_task],
        test_inputs=stream.test_inputs,
        test_targets=stream.test_targets,
        strategy=(
            f"continual stream of {stream.n_tasks} linear tasks, "
            f"{stream.samples_per_task} samples each, presented in order without boundaries"
        ),
        metadata={
            "n_tasks": stream.n_tasks,
            "samples_per_task": stream.samples_per_task,
            "d_in": int(stream.inputs.shape[1]),
            "d_out": int(stream.targets.shape[1]),
        },
    )


class StreamingEstimator:
    """Adapts a nested learner to the ``fit``/``predict`` interface.

    Using the same contract as the scikit-learn baselines means these records go through
    the sanctioned non-Torch path rather than a third record writer.

    Attributes:
        config: The learner's configuration.
        boundary: Reset the gradient memory every ``boundary`` samples. ``None`` never
            resets.
        self_referential: Use the equation-58 learner.
    """

    def __init__(
        self,
        config: LearnerConfig,
        *,
        boundary: int | None = None,
        self_referential: bool = False,
    ) -> None:
        """Create the estimator.

        Args:
            config: Learner configuration.
            boundary: Samples between gradient-memory resets.
            self_referential: Build a :class:`SelfReferentialLearner` instead.
        """

        self.config = config
        self.boundary = boundary
        self.self_referential = self_referential
        self.learner: NestedLearner | None = None

    def fit(self, x: Any, y: Any) -> StreamingEstimator:
        """Stream the samples through the learner, in order.

        Args:
            x: Shape ``(N, d_in)``.
            y: Shape ``(N, d_out)``.

        Returns:
            ``self``.
        """

        inputs = torch.as_tensor(np.asarray(x), dtype=torch.float32)
        targets = torch.as_tensor(np.asarray(y), dtype=torch.float32)
        if targets.ndim == 1:
            targets = targets.unsqueeze(-1)

        learner = (
            SelfReferentialLearner(self.config)
            if self.self_referential
            else NestedLearner(self.config)
        )
        for index in range(inputs.shape[0]):
            if self.boundary is not None and index > 0 and index % self.boundary == 0:
                learner.reset_gradient_memory()
            learner.step(inputs[index], targets[index])

        self.learner = learner
        return self

    def predict(self, x: Any) -> Any:
        """Return predictions for a batch.

        Args:
            x: Shape ``(N, d_in)``.

        Returns:
            Shape ``(N, d_out)`` NumPy array.

        Raises:
            RuntimeError: If called before ``fit``.
        """

        if self.learner is None:
            raise RuntimeError("predict called before fit")
        inputs = torch.as_tensor(np.asarray(x), dtype=torch.float32)
        return self.learner.predict(inputs).numpy()


@dataclass(frozen=True, slots=True)
class HopeExperimentConfig:
    """Settings for the Nested Learning experiment suite.

    Attributes:
        seeds: Seeds used for every learner.
        learning_rate_grid: Rates searched per learner on the validation split.
        n_tasks: Tasks in the continual stream.
        samples_per_task: Training samples per task.
        d_in: Input width.
        d_out: Output width.
        few_shot_samples: Samples allowed for the few-shot adaptation probe.
    """

    seeds: tuple[int, ...] = (0, 1, 2, 3, 4)
    learning_rate_grid: tuple[float, ...] = (0.003, 0.01, 0.03)
    n_tasks: int = 4
    samples_per_task: int = 200
    d_in: int = 8
    d_out: int = 4
    few_shot_samples: int = 20


def learner_zoo() -> dict[str, tuple[str, dict[str, Any], str]]:
    """Return the learners under comparison.

    Returns:
        Mapping from label to ``(variant, estimator kwargs, notes)``.
    """

    return {
        "one_level": (
            "one-level",
            {"use_gradient_memory": False},
            "Plain gradient descent: a single associative memory over the data stream "
            "(source eqs. 1 and 8).",
        ),
        "two_level": (
            "two-level",
            {"use_gradient_memory": True},
            "Gradient descent with momentum, read as a second level whose state is an "
            "associative memory over gradients (eqs. 10-13).",
        ),
        "two_level_slow": (
            "two-level-slow",
            {"use_gradient_memory": True, "momentum_period": 4},
            "The gradient-memory level updates once every four samples, making it a "
            "genuinely slower timescale.",
        ),
        "two_level_reset": (
            "two-level-reset",
            {"use_gradient_memory": True, "reset_at_boundary": True},
            "Momentum discarded at every task boundary. Tests the source's claim that "
            "knowledge about the loss landscape lives in the gradient memory.",
        ),
        "self_referential": (
            "self-referential",
            {"use_gradient_memory": False, "self_referential": True},
            "Equation 58: the target value is generated by the memory's own state.",
        ),
    }


def _build_factory(
    settings: HopeExperimentConfig,
    kwargs: dict[str, Any],
    learning_rate: float,
    boundary: int,
) -> Callable[[int], StreamingEstimator]:
    """Return a seeded estimator factory for one learner variant."""

    options = dict(kwargs)
    self_referential = bool(options.pop("self_referential", False))
    reset = bool(options.pop("reset_at_boundary", False))
    config = LearnerConfig(
        d_in=settings.d_in, d_out=settings.d_out, learning_rate=learning_rate, **options
    )

    def factory(seed: int) -> StreamingEstimator:
        seed_everything(seed)
        return StreamingEstimator(
            config,
            boundary=boundary if reset else None,
            self_referential=self_referential,
        )

    return factory


def select_learning_rate(
    settings: HopeExperimentConfig, kwargs: dict[str, Any], split: SupervisedSplit, boundary: int
) -> tuple[float, dict[str, float]]:
    """Pick a learning rate on the validation split.

    The two-level learner's effective step is ``eta / (1 - decay)``, so a shared rate
    would compare step sizes rather than level structures.

    Args:
        settings: Track settings.
        kwargs: Estimator options for this variant.
        split: The stream, wrapped as a split.
        boundary: Samples per task, used for the reset variant.

    Returns:
        ``(best_learning_rate, {rate: validation_mse})``.
    """

    scores: dict[str, float] = {}
    best_rate = settings.learning_rate_grid[0]
    best_score = float("inf")

    for rate in settings.learning_rate_grid:
        estimator = _build_factory(settings, kwargs, rate, boundary)(0)
        estimator.fit(split.train_inputs.numpy(), split.train_targets.numpy())
        predictions = torch.as_tensor(estimator.predict(split.val_inputs.numpy()))
        score = mean_squared_error(predictions, split.val_targets)
        if not torch.isfinite(torch.tensor(score)):
            score = float("inf")
        scores[f"{rate:g}"] = score
        if score < best_score:
            best_score, best_rate = score, rate

    return best_rate, scores


def run_stream(
    stream: ContinualStream,
    settings: HopeExperimentConfig,
    output_dir: Path,
    *,
    name: str,
) -> dict[str, RunGroup]:
    """Run every learner on one continual stream.

    Args:
        stream: The stream.
        settings: Track settings.
        output_dir: Directory receiving records.
        name: Dataset label.

    Returns:
        Mapping from label to :class:`RunGroup`.
    """

    split = stream_to_split(stream, name=name)
    groups: dict[str, RunGroup] = {}

    for label, (variant, kwargs, notes) in learner_zoo().items():
        rate, scores = select_learning_rate(settings, kwargs, split, stream.samples_per_task)
        groups[label] = run_external_baseline(
            _build_factory(settings, kwargs, rate, stream.samples_per_task),
            split,
            spec=RunSpec(
                track=TRACK,
                architecture="nested_learner",
                metric_name="test_mse_all_tasks",
                higher_is_better=False,
                variant=variant,
                architecture_version=ARCHITECTURE_VERSION,
                extra_config={
                    **split.metadata,
                    **kwargs,
                    "learning_rate_grid": list(settings.learning_rate_grid),
                    "learning_rate_validation_mse": scores,
                    "selected_learning_rate": rate,
                },
                notes=(
                    f"{notes} parameter_count is 0 for these learners: the level states are "
                    "not nn.Parameters, and the model is a single d_out x d_in matrix."
                ),
            ),
            metric_fn=mean_squared_error,
            output_dir=output_dir,
            seeds=settings.seeds,
        )
    return groups


def write_continual_diagnostics(settings: HopeExperimentConfig, output_dir: Path) -> Path:
    """Serialize the per-task diagnostics that a single aggregate metric cannot show.

    Three things live here:

    1. **Forgetting curve** — test error on every task after the whole stream, so
       retention can be read per task rather than as an average.
    2. **Level-frequency audit** — update counts per level, which is what makes the
       "different timescales" claim checkable rather than asserted.
    3. **Few-shot adaptation after a long history** — error on a fresh task after only a
       handful of samples.

    Args:
        settings: Track settings.
        output_dir: Directory receiving the artefact.

    Returns:
        Path of the written file.
    """

    from modern_nn_lab.tracks.hope import NestedTrace

    stream = make_continual_stream(
        n_tasks=settings.n_tasks,
        samples_per_task=settings.samples_per_task,
        d_in=settings.d_in,
        d_out=settings.d_out,
        seed=1729,
    )
    split = stream_to_split(stream, name="continual")

    per_task: list[dict[str, object]] = []
    frequency: dict[str, dict[str, int]] = {}
    few_shot: dict[str, float] = {}

    for variant, kwargs, _ in learner_zoo().values():
        rate, _ = select_learning_rate(settings, kwargs, split, stream.samples_per_task)
        estimator = _build_factory(settings, kwargs, rate, stream.samples_per_task)(0)
        estimator.fit(stream.inputs.numpy(), stream.targets.numpy())
        assert estimator.learner is not None

        predictions = torch.as_tensor(estimator.predict(stream.test_inputs.numpy()))
        errors = {
            int(task): mean_squared_error(
                predictions[stream.test_task_index == task],
                stream.test_targets[stream.test_task_index == task],
            )
            for task in range(stream.n_tasks)
        }
        per_task.append(
            {"learner": variant, "selected_learning_rate": rate, "per_task_mse": errors}
        )

        frequency[variant] = {
            "data_memory_steps": estimator.learner.data_state.steps,
            "gradient_memory_steps": (
                estimator.learner.gradient_state.steps
                if estimator.learner.gradient_state is not None
                else 0
            ),
            "samples_seen": int(stream.inputs.shape[0]),
        }

        # Few-shot adaptation on a fresh task, continuing from the trained state.
        fresh = make_continual_stream(
            n_tasks=1,
            samples_per_task=settings.few_shot_samples,
            d_in=settings.d_in,
            d_out=settings.d_out,
            seed=4242,
        )
        trace = NestedTrace()
        for index in range(fresh.inputs.shape[0]):
            estimator.learner.step(fresh.inputs[index], fresh.targets[index], trace)
        few_shot[variant] = mean_squared_error(
            estimator.learner.predict(fresh.test_inputs), fresh.test_targets
        )

    conflicting = make_continual_stream(
        n_tasks=settings.n_tasks,
        samples_per_task=settings.samples_per_task,
        d_in=settings.d_in,
        d_out=settings.d_out,
        seed=1729,
        conflicting=True,
    )
    conflict_split = stream_to_split(conflicting, name="conflicting")
    conflict: dict[str, float] = {}
    for variant, kwargs, _ in learner_zoo().values():
        rate, _ = select_learning_rate(
            settings, kwargs, conflict_split, conflicting.samples_per_task
        )
        estimator = _build_factory(settings, kwargs, rate, conflicting.samples_per_task)(0)
        estimator.fit(conflicting.inputs.numpy(), conflicting.targets.numpy())
        predictions = torch.as_tensor(estimator.predict(conflicting.test_inputs.numpy()))
        conflict[variant] = mean_squared_error(predictions, conflicting.test_targets)

    payload = {
        "schema_version": RESULT_SCHEMA_VERSION,
        "track": TRACK,
        "measurement": "continual_learning_diagnostics",
        "note": (
            "Single seed. These curves show shape, not uncertainty; the seeded comparison "
            "is in the records."
        ),
        "forgetting_curve": per_task,
        "level_update_frequency": frequency,
        "few_shot_after_long_history_mse": few_shot,
        "conflicting_tasks_mse": conflict,
    }
    artefacts = output_dir / ARTEFACT_DIRNAME
    artefacts.mkdir(parents=True, exist_ok=True)
    path = artefacts / "continual_diagnostics.json"
    path.write_text(json.dumps(payload, indent=2, default=float) + "\n", encoding="utf-8")
    return path


def run(output_dir: Path | str | None = None, *, quick: bool = False) -> None:
    """Run the whole Nested Learning suite.

    Args:
        output_dir: Destination directory. Defaults to ``results/hope``.
        quick: Reduced seeds and stream length for smoke-testing the protocol.
    """

    destination = Path(output_dir) if output_dir is not None else Path("results") / TRACK
    settings = (
        HopeExperimentConfig(
            seeds=(0, 1), n_tasks=2, samples_per_task=60, learning_rate_grid=(0.01,)
        )
        if quick
        else HopeExperimentConfig()
    )

    stream = make_continual_stream(
        n_tasks=settings.n_tasks,
        samples_per_task=settings.samples_per_task,
        d_in=settings.d_in,
        d_out=settings.d_out,
        seed=1729,
    )
    run_stream(stream, settings, destination, name="continual")

    conflicting = make_continual_stream(
        n_tasks=settings.n_tasks,
        samples_per_task=settings.samples_per_task,
        d_in=settings.d_in,
        d_out=settings.d_out,
        seed=1729,
        conflicting=True,
    )
    run_stream(conflicting, settings, destination, name="conflicting")

    write_continual_diagnostics(settings, destination)
